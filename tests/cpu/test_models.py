# ----------------------------------------------------------------- B3 / B4
def _small(kind, eps, **kw):
    return build_model(kind, stats=fit_stats(eps), cfg=ModelConfig(latent=24, embed=12, hidden=40, resid_hidden=40, **kw), dt=DT, physics=PH)


def _zero_last(layer):
    with torch.no_grad():
        layer[-1].weight.zero_(); layer[-1].bias.zero_()


@pytest.mark.parametrize("kind", ["b3", "b4"])
def test_zero_residual_reduces_to_physics_only(kind):
    eps = [synthetic_episode("a", 1), synthetic_episode("b", 2)]
    ds = ModelReadyDataset(eps, BCFG); b = batch_of(ds, 8)
    m = _small(kind, eps).eval(); _zero_last(m.resid)
    p1 = build_model("b1", physics=PH).predict(b, 8)
    assert (m.predict(b, 8) - p1).abs().max() < 1e-4


@pytest.mark.parametrize("kind", ["b3", "b4"])
def test_residual_models_shapes_unit_quaternion_and_no_future_leak(kind):
    eps = [synthetic_episode("a", 1), synthetic_episode("b", 2)]
    ds = ModelReadyDataset(eps, BCFG); b = batch_of(ds, 6); m = _small(kind, eps).eval()
    out = m(b, 7)
    assert out["pred"].shape == (6, 7, 13) and torch.isfinite(out["pred"]).all()
    assert torch.allclose(out["pred"][..., 6:10].norm(dim=-1), torch.ones(6, 7), atol=1e-4)
    b2 = {k: v.clone() for k, v in b.items()}; b2["future_states"] = b2["future_states"] * 0 + 3.0
    assert torch.allclose(m.predict(b, 5), m.predict(b2, 5))
    if kind == "b4":
        assert out["dec"] is None
        with pytest.raises(ValueError):
            m(b, 3, "decoder")
    else:
        assert out["dec"].shape == (6, 10, 13)
        assert torch.isfinite(m(b, 3, "decoder")["pred"]).all()


def test_b3_uses_latent_and_b4_does_not():
    eps = [synthetic_episode("a", 1)]
    ds = ModelReadyDataset(eps, BCFG); b = batch_of(ds, 4)
    m3, m4 = _small("b3", eps).eval(), _small("b4", eps).eval()
    with torch.no_grad():                                     # make the residual output non-zero
        for m in (m3, m4):
            m.resid[-1].weight.normal_(0, 0.5)
    b2 = {k: v.clone() for k, v in b.items()}; b2["obs_history"] = b2["obs_history"] + 5.0      # change the IMU only
    assert not torch.allclose(m3.predict(b, 5), m3.predict(b2, 5), atol=1e-6)                    # B3 reads the IMU through h
    assert torch.allclose(m4.predict(b, 5), m4.predict(b2, 5))                                   # B4 cannot


def test_acc_only_mask_zeroes_kinematic_corrections():
    eps = [synthetic_episode("a", 1)]
    m = _small("b3", eps, residual_channels="acc_only").eval()
    with torch.no_grad():
        m.resid[-1].weight.normal_(0, 1.0); m.resid[-1].bias.normal_(0, 1.0)
    r = m.residual(torch.randn(3, 24), torch.tensor(eps[0].states[:3]), torch.tensor(eps[0].actions[:3]))
    assert r[:, 0:3].abs().max() == 0 and r[:, 6:9].abs().max() == 0 and r[:, 3:6].abs().max() > 0
    with pytest.raises(ValueError):
        _small("b3", eps, residual_channels="bogus")


