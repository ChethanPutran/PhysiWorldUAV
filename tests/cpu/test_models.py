def test_evaluator_orders_models_and_reliable_horizon():
    ds = ModelReadyDataset([synthetic_episode("a", 1, wind_acc=(0, 0, 0)), synthetic_episode("b", 2)], BCFG)
    r1 = evaluate(build_model("b1", physics=PH), ds, horizon=10, ks=(1, 5, 10))
    r0 = evaluate(build_model("b0"), ds, horizon=10, ks=(1, 5, 10))
    assert r1["pos_rmse_m"]["10"] < r0["pos_rmse_m"]["10"] and r1["finite"]
    assert r1["n_episodes"] == 2 and r1["n_windows"] == len(ds)
    assert "pos_rmse_m_last_k_ci95" in r1
    for k in ("1", "10"):                       # RMSE >= mean error (Jensen), both reported
        assert r1["pos_rmse_m"][k] >= r1["pos_mean_m"][k] - 1e-12
    pred = torch.zeros(2, 4, 13); tgt = torch.zeros(2, 4, 13); tgt[0, 2, 0] = 1.0
    assert reliable_horizon(pred, tgt, 0.5).tolist() == [2.0, 4.0]
    assert evaluate(build_model("b0"), ModelReadyDataset([], BCFG), horizon=10)["n_windows"] == 0


