def _b2(eps, **kw):
    return build_model("b2", stats=fit_stats(eps), cfg=ModelConfig(latent=32, embed=16, hidden=48, **kw), dt=DT)


def test_b2_shapes_unit_quaternion_translation_invariance_and_start_options():
    eps = [synthetic_episode("a", 1), synthetic_episode("b", 2)]
    ds = ModelReadyDataset(eps, BCFG); m = _b2(eps).eval(); b = batch_of(ds, 6)
    for init in ("given", "decoder"):
        out = m(b, 7, init)
        assert out["pred"].shape == (6, 7, 13) and out["dec"].shape == (6, 10, 13)
        assert torch.isfinite(out["pred"]).all()
        assert torch.allclose(out["pred"][..., 6:10].norm(dim=-1), torch.ones(6, 7), atol=1e-4)
    shifted = {k: v.clone() for k, v in b.items()}
    for k in ("state_history", "future_states"):
        shifted[k][..., 0:3] += torch.tensor([10.0, -5.0, 3.0])
    d = (m.predict(shifted, 7) - m.predict(b, 7))[..., 0:3]
    assert torch.allclose(d, torch.tensor([10.0, -5.0, 3.0]).expand_as(d), atol=1e-4)      # only the offset changes
    with pytest.raises(ValueError):
        m(b, 3, "nope")


