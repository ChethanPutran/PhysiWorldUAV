def _cfg(**kw):
    base = dict(kind="b2", epochs=4, batch_size=64, lr=3e-3, warmup_steps=5, latent=24, embed=12, hidden=40,
                horizon_stages=[10], seed=3, device="cpu", patience=50)
    base.update(kw)
    return TrainConfig(**base)


def test_tiny_overfit_loss_drops(tmp_path):
    wind = (0.8, -0.4, 0.2)
    eps = [synthetic_episode(f"e{i}", i, wind_acc=wind) for i in range(3)]
    s = train(tmp_path / "ds", tmp_path / "run", _cfg(epochs=40, tiny_episodes=3, lr=3e-3), episodes=(eps, []), log=lambda *_: None)
    import json
    rec = [json.loads(l) for l in (tmp_path / "run" / "metrics.jsonl").read_text().splitlines()]
    assert rec[-1]["train"]["total"] < 0.1 * rec[0]["train"]["total"]
    assert (tmp_path / "run" / "checkpoints" / "last.pt").exists() and s["epochs"] == 40


def test_resume_equals_continuous_training(tmp_path):
    eps = [synthetic_episode(f"e{i}", i, wind_acc=(0.5, 0, 0)) for i in range(3)]
    val = [synthetic_episode("v0", 9, wind_acc=(0.5, 0, 0))]
    train(tmp_path / "d", tmp_path / "full", _cfg(epochs=4), episodes=(eps, val), log=lambda *_: None)
    train(tmp_path / "d", tmp_path / "part", _cfg(epochs=4), episodes=(eps, val), log=lambda *_: None, max_epochs=2)   # "crash" after 2
    train(tmp_path / "d", tmp_path / "part", _cfg(epochs=4), episodes=(eps, val), resume=True, log=lambda *_: None)
    from physiworld_uav.training import checkpoint as ck
    a = ck.load(tmp_path / "full" / "checkpoints" / "last.pt"); b = ck.load(tmp_path / "part" / "checkpoints" / "last.pt")
    assert a["epoch"] == b["epoch"] == 4
    for k in a["model"]:
        assert torch.allclose(a["model"][k], b["model"][k], atol=1e-6), k


