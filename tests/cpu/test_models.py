def test_loss_zero_at_target_and_rotation_term_is_angle_squared():
    ds = ModelReadyDataset([synthetic_episode("a", 1)], BCFG); b = batch_of(ds, 4)
    tgt = b["future_states"]
    t0 = state_terms(tgt, tgt)
    assert all(v.abs().max() < 1e-6 for v in t0.values())
    pred = tgt.clone(); pred[..., 6:10] = quat.mul(quat.from_rotation_vector(torch.tensor([0.0, 0.0, 0.2])), tgt[..., 6:10])
    assert torch.allclose(state_terms(pred, tgt)["R"], torch.full(tgt.shape[:-1], 0.04), atol=1e-5)
    out = {"pred": tgt, "dec": b["state_history"]}
    parts = total_loss(out, b, 10, LossWeights())
    assert parts["total"].abs() < 1e-6


def test_loss_weights_fit_and_gradients_flow():
    eps = [synthetic_episode("a", 1), synthetic_episode("b", 2)]
    ds = ModelReadyDataset(eps, BCFG)
    w = fit_loss_weights(ds, 10)
    assert min(w.p, w.v, w.R, w.w) > 0
    m = _b2(eps); b = batch_of(ds, 8)
    parts = total_loss(m(b, 10), b, 10, w)
    parts["total"].backward()
    assert all(p.grad is not None and torch.isfinite(p.grad).all() for p in m.parameters())
    # lambda_roll is rescaled by the discount sum: the horizon does not change the loss scale much
    w2 = LossWeights(gamma=0.99)
    a = total_loss({"pred": b["future_states"][:, :5] + 0.1, "dec": None}, b, 5, w2)["total"]
    c = total_loss({"pred": b["future_states"] + 0.1, "dec": None}, b, 10, w2)["total"]
    assert 0.3 < (a / c).item() < 3.0


