DT = 0.02
PH = QuadrotorPhysics.from_yaml()
HOVER = float(np.sqrt(PH.mass * PH.g / (4 * PH.kf[0].item())))


def synthetic_episode(eid: str, seed: int, n: int = 90, wind_acc=(0.0, 0.0, 0.0)) -> ModelEpisode:
    """Episode generated by f_phys itself (+ a constant 'wind' acceleration): B1 is exact when wind = 0."""
    rng = np.random.default_rng(seed)
    s = torch.zeros(13); s[6] = 1.0
    s[3:6] = torch.tensor(rng.normal(0, 0.3, 3), dtype=torch.float32)
    s[6:10] = quat.from_rotation_vector(torch.tensor(rng.normal(0, 0.05, 3), dtype=torch.float32))
    extra = torch.zeros(12); extra[3:6] = torch.tensor(wind_acc, dtype=torch.float32)
    u = torch.full((4,), HOVER)
    states, acts, obs = [s.clone()], [], []
    for _ in range(n):
        u = (u + torch.tensor(rng.normal(0, 4.0, 4), dtype=torch.float32)).clamp(300, 600)
        dd = PH.derivative(s, u, extra)
        R = quat.to_rotation_matrix(s[6:10])
        f_spec = R.T @ (dd[3:6] + torch.tensor([0, 0, PH.g]))
        obs.append(torch.cat([f_spec, s[10:13]]).numpy())
        s = rk4_step(lambda x, u=u: PH.derivative(x, u, extra), s, DT, PH.project)
        states.append(s.clone()); acts.append(u.clone())
    obs.append(obs[-1])
    return ModelEpisode(episode_id=eid, meta=None, t=np.arange(n + 1) * DT, states=torch.stack(states).numpy(),
                        obs=np.stack(obs).astype(np.float32), actions=torch.stack(acts).numpy(), dt=DT, aux={})


BCFG = BuilderConfig(decimation=4, history=10, horizon=10)


def batch_of(ds, n=8):
    items = [ds[i] for i in range(min(n, len(ds)))]
    return {k: torch.stack([it[k] for it in items]) for k in
            ("state_history", "obs_history", "action_history", "future_actions", "future_states")}


# ----------------------------------------------------------------- quaternion
def test_rotation_vector_round_trip_and_geodesic():
    rv = torch.tensor([[0.3, -0.2, 0.5], [0.0, 0.0, 0.0], [1e-9, 0, 0], [0.0, 2.5, 0.0]])
    q = quat.from_rotation_vector(rv)
    assert torch.allclose(q.norm(dim=-1), torch.ones(4), atol=1e-6)
    assert torch.allclose(quat.to_rotation_vector(q), rv, atol=1e-5)
    assert torch.allclose(quat.geodesic_angle(q, -q), torch.zeros(4), atol=1e-6)       # sign invariant
    assert torch.allclose(quat.geodesic_angle(q, quat.from_rotation_vector(torch.zeros(4, 3))), rv.norm(dim=-1), atol=1e-5)


def test_geodesic_gradient_finite_at_zero():
    q = torch.tensor([[1.0, 0, 0, 0]], requires_grad=True)
    quat.geodesic_angle(q, torch.tensor([[1.0, 0, 0, 0]])).square().sum().backward()
    assert torch.isfinite(q.grad).all()


def test_rotation_matrix_is_orthonormal_and_geodesic_matches_matrix_angle():
    q1 = quat.from_rotation_vector(torch.tensor([0.4, 0.1, -0.7])); q2 = quat.from_rotation_vector(torch.tensor([-0.2, 0.3, 0.1]))
    R1, R2 = quat.to_rotation_matrix(q1), quat.to_rotation_matrix(q2)
    assert torch.allclose(R1 @ R1.T, torch.eye(3), atol=1e-6)
    ang = torch.acos(((R1.T @ R2).diagonal().sum() - 1) / 2)
    assert torch.allclose(quat.geodesic_angle(q1, q2), ang, atol=1e-5)


# ----------------------------------------------------------------- f_phys
def test_hover_trim_and_free_fall():
    s = torch.zeros(13); s[6] = 1.0
    d = PH.derivative(s, torch.full((4,), HOVER))
    assert d[3:6].abs().max() < 1e-4 and d[10:13].abs().max() < 1e-6
    d0 = PH.derivative(s, torch.zeros(4))
    assert torch.allclose(d0[3:6], torch.tensor([0, 0, -PH.g]), atol=1e-6)


def test_torques_and_rk4_keeps_unit_quaternion():
    s = torch.zeros(13); s[6] = 1.0
    u = torch.full((4,), HOVER); u[0] += 30                        # unequal rotors → roll/pitch torque
    d = PH.derivative(s, u)
    assert d[10:13].abs().max() > 0
    for _ in range(200):
        s = rk4_step(lambda x: PH.derivative(x, u), s, DT, PH.project)
    assert abs(s[6:10].norm().item() - 1) < 1e-5


def test_physics_batched_matches_single():
    ep = synthetic_episode("e", 0)
    S, U = torch.tensor(ep.states[:5]), torch.tensor(ep.actions[:5])
    batched = PH.derivative(S, U)
    for i in range(5):
        assert torch.allclose(batched[i], PH.derivative(S[i], U[i]), atol=1e-5)


