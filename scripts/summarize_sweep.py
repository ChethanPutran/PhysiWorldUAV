#!/usr/bin/env python3
"""Summarise sweep fix_v1: per model/variant mean ± sd over seeds of the evaluation (outputs/eval/fx_*_c*.json), training facts
(best epoch, epochs, time) from outputs/experiments/*/summary.json, figures and SUMMARY.md in outputs/reports/sweep_fix_v1/.

Run names fx_<ds>_<model>[_<variant>]_s<seed>; the earlier v06_b3 counts as seed 0 of "b3 base" on v06 (the checkpoint bug did not
affect it). Reference rows (B0, B1, B6a, and the B6b of the first comparison) come from outputs/eval/v06.json / v05.json."""
from __future__ import annotations

import csv
import glob
import json
import re
import statistics as S
from collections import defaultdict
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

OUT = Path("outputs/reports/sweep_fix_v1"); (OUT / "tables").mkdir(parents=True, exist_ok=True); (OUT / "figures").mkdir(exist_ok=True)
ROLES = [("val_id", "val ID"), ("test_id", "test ID"), ("test_ood_magnitude", "OOD magnitude"), ("test_ood_direction", "OOD direction"),
         ("test_ood_temporal", "OOD temporal"), ("test_ood_gust", "OOD gust"), ("test_ood_physics", "OOD physics"), ("test_ood_trajectory", "OOD trajectory")]
NAME = {"b2": "B2 pure neural", "b3": "B3 physics+residual+memory", "b4": "B4 no memory", "b4_rw": "B4 (B3 width)", "b5a": "B5a learned field", "b5b": "B5b learned dynamics"}
VAR = {"": "base", "b3a": "B3a: no action in residual", "b3b": "B3b: zero-residual penalty", "b3c": "B3c: shared trunk",
       "lr2e-4": "lr 2e-4", "wd1e-2": "weight decay 1e-2", "lr2e-4_wd1e-2": "lr 2e-4 + wd 1e-2"}
RE = re.compile(r"^fx_(v0\d)_(b2|b3|b4_rw|b4|b5a|b5b)(?:_(.+?))?_s(\d+)$")

ev: dict[str, dict] = {}
for f in glob.glob("outputs/eval/fx_v0?_c?.json"):
    ev.update(json.load(open(f)))
ref = {}
for t in ("v05", "v06"):
    ref[t] = json.load(open(f"outputs/eval/{t}.json"))

runs = []                                              # (ds, model, variant, seed, name)
for name in ev:
    m = RE.match(name)
    if m:
        runs.append((m.group(1), m.group(2), m.group(3) or "", int(m.group(4)), name))
    elif name == "v06_b3":
        runs.append(("v06", "b3", "", 0, name))
groups = defaultdict(list)
for ds, model, var, seed, name in runs:
    groups[(ds, model, var)].append((seed, name))


def val(name, role, k="20"):
    r = ev[name].get(role) or {}
    return r.get("pos_rmse_m", {}).get(k)


def info(name):
    p = Path("outputs/experiments") / name / "summary.json"
    return json.load(open(p)) if p.exists() else {}


def ms(xs):
    xs = [x for x in xs if x is not None]
    return (S.mean(xs), S.stdev(xs) if len(xs) > 1 else float("nan"), len(xs)) if xs else (float("nan"), float("nan"), 0)


def cell(xs, nd=3):
    m, s, n = ms(xs)
    return "–" if n == 0 else (f"{m:.{nd}f}" if n == 1 else f"{m:.{nd}f} ± {s:.{nd}f}")


md = ["# Sweep fix_v1: results (generated by scripts/summarize_sweep.py)", "",
      "Position RMSE at 20 steps (0.4 s) [m], mean ± standard deviation over seeds (n = number of seeds; with n = 1 only the value). "
      "Every run is evaluated at its best validation checkpoint (fixed trainer). The OOD roles have 4–7 episodes; one dataset per row group.", ""]
rows_csv = []
for ds in ("v06", "v05"):
    gs = sorted([g for g in groups if g[0] == ds], key=lambda g: (g[1], g[2]))
    if not gs:
        continue
    md += [f"## Dataset {'v0.6.0' if ds == 'v06' else 'v0.5.0'}", "", "| Model / variant | n | " + " | ".join(l for _, l in ROLES) + " |", "|---|---|" + "---|" * len(ROLES)]
    for g in gs:
        names = [n for _, n in sorted(groups[g])]
        label = NAME[g[1]] + ("" if g[2] == "" else f" · {VAR.get(g[2], g[2])}")
        cells = [cell([val(n, r) for n in names]) for r, _ in ROLES]
        md.append(f"| {label} | {len(names)} | " + " | ".join(cells) + " |")
        for r, l in ROLES:
            m_, s_, n_ = ms([val(n, r) for n in names]); rows_csv.append([ds, g[1], g[2], r, n_, m_, s_])
    cvp = Path("outputs/eval/constant_velocity_v06.json")
    if ds == "v06" and cvp.exists():                       # scripts/constant_velocity_baseline.py: zero-acceleration extrapolation of the true state
        cv = json.load(open(cvp))
        md.append("| Constant velocity (reference, no learning) | – | " + " | ".join(f"{cv[r]:.3f}" if r in cv else "–" for r, _ in ROLES) + " |")
    for key, lab in (("b0", "B0 hold"), ("b1", "B1 physics only"), ("b6a_future", "B6a oracle wrench (future)")):
        src = ref[ds] if ds in ref else None
        if src and key in src:
            md.append(f"| {lab} (reference) | – | " + " | ".join(f"{src[key][r]['pos_rmse_m']['20']:.3f}" if r in src[key] and src[key][r].get('pos_rmse_m') else "–" for r, _ in ROLES) + " |")
    md.append("")

# one-step (k=1) for the B3 family on v06
md += ["## B3 variants on v0.6.0, per seed (test ID and OOD magnitude, 20 steps)", "",
       "| Run | Seed | Best epoch | Epochs | Val best [m] | Test ID | OOD magnitude | OOD physics | OOD direction |", "|---|---|---|---|---|---|---|---|---|"]
for g in sorted([g for g in groups if g[0] == "v06" and g[1] == "b3"], key=lambda g: g[2]):
    for seed, n in sorted(groups[g]):
        i = info(n)
        md.append(f"| {VAR.get(g[2], g[2])} | {seed} | {i.get('best_epoch', '–')} | {i.get('epochs', '–')} | {i.get('best_metric', float('nan')):.4f} | "
                  + " | ".join(f"{val(n, r):.4f}" if val(n, r) is not None else "–" for r in ("test_id", "test_ood_magnitude", "test_ood_physics", "test_ood_direction")) + " |")
md.append("")

# training facts per group
md += ["## Training facts per model/variant (mean over seeds)", "", "| Dataset | Model / variant | n | Best epoch | Epochs run | Best val [m] | Last-epoch val [m] | Train time [min] |", "|---|---|---|---|---|---|---|---|"]
for g in sorted(groups, key=lambda g: (g[0], g[1], g[2])):
    names = [n for _, n in groups[g]]
    infos = [info(n) for n in names]
    last = []
    for n in names:
        p = Path("outputs/experiments") / n / "metrics.jsonl"
        if p.exists():
            L = [json.loads(l) for l in p.read_text().splitlines() if l.strip()]
            last.append(L[-1]["metric"])
    tm = [sum(json.loads(l)["epoch_s"] for l in (Path("outputs/experiments") / n / "metrics.jsonl").read_text().splitlines() if l.strip()) / 60 for n in names if (Path("outputs/experiments") / n / "metrics.jsonl").exists()]
    md.append(f"| {g[0]} | {NAME[g[1]]}" + ("" if g[2] == "" else f" · {VAR.get(g[2], g[2])}") + f" | {len(names)} | {cell([i.get('best_epoch') for i in infos], 1)} | {cell([i.get('epochs') for i in infos], 1)} | "
              f"{cell([i.get('best_metric') for i in infos], 4)} | {cell(last, 4)} | {cell(tm, 1)} |")
md.append("")
(OUT / "SUMMARY.md").write_text("\n".join(md))
with open(OUT / "tables" / "summary_by_group.csv", "w", newline="") as f:
    w = csv.writer(f); w.writerow(["dataset", "model", "variant", "role", "n_seeds", "mean_pos_rmse_20_m", "sd"]); w.writerows(rows_csv)

# figure: seed dots per variant for the B3 family, ID and OOD roles (v06)
fam = sorted([g for g in groups if g[0] == "v06" and g[1] == "b3"], key=lambda g: g[2])
pal = ["#0072B2", "#E69F00", "#009E73", "#CC79A7"]
if fam:
    fig, axs = plt.subplots(1, 4, figsize=(15, 3.6), sharey=False)
    for ax, (role, lab) in zip(axs, [r for r in ROLES if r[0] in ("test_id", "test_ood_magnitude", "test_ood_physics", "test_ood_direction")]):
        for i, g in enumerate(fam):
            ys = [val(n, role) for _, n in sorted(groups[g])]
            ys = [y for y in ys if y is not None]
            ax.scatter([i] * len(ys), ys, s=28, color=pal[i % 4], zorder=3)
            if ys:
                ax.hlines(S.mean(ys), i - 0.3, i + 0.3, color=pal[i % 4], lw=2)
        ax.set_xticks(range(len(fam))); ax.set_xticklabels([VAR.get(g[2], g[2]).split(":")[0] for g in fam], fontsize=8)
        ax.set_title(lab, fontsize=10); ax.grid(axis="y", alpha=0.3); ax.set_ylabel("pos RMSE @20 [m]" if role == "test_id" else "")
    fig.suptitle("B3 variants on v0.6.0: one dot per seed, bar = mean"); fig.tight_layout(); fig.savefig(OUT / "figures" / "b3_variants_seed_dots.png", dpi=140); plt.close(fig)
print("wrote", OUT / "SUMMARY.md")
