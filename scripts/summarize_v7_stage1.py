#!/usr/bin/env python3
"""Summary of the v7 stage-1 evaluation: models x roles table of the 20-step (1 s) position RMSE, one-step and 5-step errors, attitude error,
training facts, and a bar chart. Reads outputs/eval/st_v07_c*.json, outputs/eval/constant_velocity_v07.json and the run summaries.
Writes outputs/reports/v7_stage1/{SUMMARY.md, tables/*.csv, figures/*.png}."""
from __future__ import annotations

import csv
import glob
import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

OUT = Path("outputs/reports/v7_stage1"); (OUT / "tables").mkdir(parents=True, exist_ok=True); (OUT / "figures").mkdir(exist_ok=True)
ROLES = [("val_id", "val ID"), ("test_id", "test ID"), ("test_ood_magnitude", "OOD magnitude"), ("test_ood_direction", "OOD direction"),
         ("test_ood_temporal", "OOD temporal"), ("test_ood_gust", "OOD gust"), ("test_ood_physics", "OOD physics"), ("test_ood_trajectory", "OOD trajectory")]
NAME = {"b0": "B0 hold", "b1": "B1 physics only", "b6a_future": "B6a oracle wrench (future)", "b6a_current": "B6a oracle wrench (current)",
        "st_v07_b3_s0": "B3 physics+residual+memory (227k)", "st_v07_b3_small_s0": "B3 small (60k)", "st_v07_b4_s0": "B4 no memory (226k)",
        "st_v07_b4_rw_s0": "B4 (B3 width, 73k)", "st_v07_b2_s0": "B2 pure neural", "st_v07_b5a_s0": "B5a learned field", "st_v07_b5b_s0": "B5b learned dynamics"}
ORDER = ["b0", "b1", "st_v07_b2_s0", "st_v07_b3_s0", "st_v07_b3_small_s0", "st_v07_b4_s0", "st_v07_b4_rw_s0", "st_v07_b5a_s0", "st_v07_b5b_s0", "b6a_future", "b6a_current"]
ev: dict = {}
for f in sorted(glob.glob("outputs/eval/st_v07_c*.json")):
    ev.update(json.load(open(f)))
cvf = Path("outputs/eval/constant_velocity_v07.json")
cv = json.load(open(cvf)) if cvf.exists() else None


def val(m, role, col="pos_rmse_m", k="20"):
    r = (ev.get(m) or {}).get(role) or {}
    x = r.get(col)
    return x.get(k) if isinstance(x, dict) else None


def table(k):
    rows = [[NAME[m]] + [("%.3f" % v if (v := val(m, r, k=k)) is not None else "–") for r, _ in ROLES] for m in ORDER if m in ev]
    if cv and k == "20":
        rows.insert(2, ["Constant velocity (no learning)"] + [("%.3f" % cv[r]) if r in cv else "–" for r, _ in ROLES])
    h = ["Model"] + [l for _, l in ROLES]
    return "| " + " | ".join(h) + " |\n|" + "---|" * len(h) + "\n" + "\n".join("| " + " | ".join(r) + " |" for r in rows) + "\n", rows


md = ["# Pilot v7, stage 1: evaluation on all roles (generated by scripts/summarize_v7_stage1.py)", "",
      "Position RMSE [m] at the stated number of 50 ms steps, open loop from the true initial state, each model at its best validation epoch, seed 0, one run per model. "
      "Roles with early-ended or out-of-envelope episodes keep completed in-envelope episodes only. Episode counts per role: " +
      ", ".join(f"{l} {ev[ORDER[0]][r]['n_episodes']}" for r, l in ROLES if ORDER[0] in ev and r in ev[ORDER[0]]) + ".", ""]
for k, lab in (("20", "20 steps (1.0 s)"), ("5", "5 steps (0.25 s)"), ("1", "1 step (50 ms)")):
    t, rows = table(k)
    md += [f"## Position RMSE at {lab}", "", t]
    with open(OUT / "tables" / f"pos_rmse_{k}.csv", "w", newline="") as f:
        w = csv.writer(f); w.writerow(["model"] + [r for r, _ in ROLES]); w.writerows(rows)
att = [[NAME[m]] + [("%.1f" % v if (v := val(m, r, "att_rmse_deg", "20")) is not None else "–") for r, _ in ROLES] for m in ORDER if m in ev]
md += ["## Attitude RMSE at 20 steps [deg]", "", "| Model | " + " | ".join(l for _, l in ROLES) + " |", "|" + "---|" * (len(ROLES) + 1), *["| " + " | ".join(r) + " |" for r in att], ""]
facts = []
for m in ORDER:
    p = Path("outputs/experiments") / m / "summary.json"
    if p.exists():
        s = json.load(open(p)); facts.append(f"| {NAME[m]} | {s['n_params']:,} | {s['epochs']} | {s['best_epoch']} | {s['best_metric']:.4f} | {s['total_wall_s'] / 3600:.1f} h | {s['stop_reason'].replace('_', ' ')} |")
md += ["## Training facts", "", "| Run | Parameters | Epochs | Best epoch | Best validation [m] | Wall time | Stopped by |", "|---|---|---|---|---|---|---|", *facts, ""]
(OUT / "SUMMARY.md").write_text("\n".join(md))

fig, ax = plt.subplots(figsize=(15, 4.8))
shown = [m for m in ORDER if m in ev and m not in ("b6a_current", "b0")]
pal = {"b1": "#888888", "b6a_future": "#444444", "st_v07_b3_s0": "#0072B2", "st_v07_b3_small_s0": "#56B4E9", "st_v07_b4_s0": "#E69F00", "st_v07_b4_rw_s0": "#D55E00",
       "st_v07_b2_s0": "#CC79A7", "st_v07_b5a_s0": "#009E73", "st_v07_b5b_s0": "#B8860B"}
w = 0.8 / (len(shown) + (1 if cv else 0))
for i, m in enumerate(shown):
    ax.bar(np.arange(len(ROLES)) + i * w, [val(m, r) or 0 for r, _ in ROLES], w, color=pal.get(m, "#999"), label=NAME[m])
if cv:
    ax.bar(np.arange(len(ROLES)) + len(shown) * w, [cv.get(r, 0) for r, _ in ROLES], w, color="#000000", alpha=0.35, label="Constant velocity")
ax.set_xticks(np.arange(len(ROLES)) + 0.4 - w / 2); ax.set_xticklabels([l for _, l in ROLES]); ax.set_ylabel("position RMSE at 20 steps (1 s) [m]")
ax.set_yscale("log"); ax.grid(axis="y", alpha=0.3); ax.legend(fontsize=7, ncol=3); ax.set_title("Pilot v7, stage 1: open-loop position error by role")
fig.tight_layout(); fig.savefig(OUT / "figures" / "pos_rmse_20_by_role.png", dpi=140)
print("wrote", OUT / "SUMMARY.md")
